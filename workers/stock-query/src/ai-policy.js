// 只拦截肯定式的操作建议和价格目标，避免把“不提供目标价”这类说明误拦。
export const AI_BLOCK_PATTERNS = [
  /目标价(位)?\s*(为|是|在|约|看|上看|：|:)\s*\d/,
  /止(损|盈)(价|位|点)?\s*(为|是|设在|设为|设|放在|：|:)\s*\d/,
  /(?<![不别勿非无没])(建议|可以考虑|不妨|应当|应该)(您|你)?\s*(立即|逢低|逢高|适当|分批)?\s*(买入|卖出|加仓|减仓|清仓|建仓|抄底|止盈|止损|满仓|空仓)/,
  /(?<![不别勿非无没])(稳赚|必涨|必跌|保证收益|保本|翻倍收益)/,
  /(仓位|持仓)\s*(控制|保持|降到|提高到|调整到|调至)\s*(在)?\s*\d+\s*(%|成)/,
  /(收益|回报)(率)?\s*(可达|将达|预计|有望达到|能达到)\s*\d/,
];

export function aiBlocked(text) {
  return AI_BLOCK_PATTERNS.some((pattern) => pattern.test(text));
}
